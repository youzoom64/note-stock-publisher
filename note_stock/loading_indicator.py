async def prepare_loading_emoji(client):
    emojis = await client.fetch_application_emojis()
    emoji = next((item for item in emojis
                  if item.name == LOADING_EMOJI_NAME and item.animated and item.available), None)
    if emoji is None:
        emoji = await client.create_application_emoji(
            name=LOADING_EMOJI_NAME, image=b64decode(_BODY_LOADING_GIF))
    client.loading_emoji = str(emoji)
    return emoji


def body_loading_text(client):
    return loading_text(client, "本文取得中")


def loading_text(client, text="処理中"):
    emoji = getattr(client, 'loading_emoji', '⏳')
    return text if text.startswith(emoji) else f"{emoji} {text}"
